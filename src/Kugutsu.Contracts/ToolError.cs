/// <summary>Writes stable error names and rejects numeric enum input.</summary>
public sealed class ErrorCodeConverter() : JsonStringEnumConverter<ErrorCode>(null, false);

/// <summary>A safe public error without arbitrary exception or input text.</summary>
public sealed class ToolError
{
    /// <summary>Creates an error. Retryability is decided by the owning handler.</summary>
    [JsonConstructor]
    public ToolError(ErrorCode code, bool retryable = false)
    {
        if (!Enum.IsDefined(code)) { throw new ArgumentOutOfRangeException(nameof(code)); }
        Code = code;
        Retryable = retryable;
    }

    [JsonPropertyName("code")]
    public ErrorCode Code { get; }

    /// <summary>Fixed diagnostic text derived exclusively from the defined code.</summary>
    [JsonPropertyName("message")]
    public string Message => Code.ToString().Replace('_', ' ').ToLowerInvariant() + ".";

    [JsonPropertyName("retryable")]
    public bool Retryable { get; }
}
